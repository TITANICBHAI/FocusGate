// The Rules nudge, in the panel (opens Settings in a new tab) and in the dashboard (switches the tab).
const { chromium } = require("playwright");
const fs = require("fs");
const S = "/tmp/claude-0/-home-claude/1d3d810c-0866-503f-8b36-d437fcdf9427/scratchpad/store";
const OUT = process.argv[2] || `${S}/out8`;
const THEME = process.argv[3] || "light";
const defaults = JSON.parse(fs.readFileSync(`${S}/default-state.json`, "utf8"));
fs.writeFileSync(`${S}/panel.html`, `<!doctype html><html lang="en" data-theme="${THEME}"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width, initial-scale=1"><title>FocusGate</title><link rel="stylesheet" href="styles.css"></head><body class="panel-page"><div id="root"></div><script src="panel.js"></script></body></html>`);
fs.writeFileSync(`${S}/dashboard.html`, `<!doctype html><html lang="en" data-theme="${THEME}"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width, initial-scale=1"><title>Dashboard</title><link rel="stylesheet" href="styles.css"></head><body class="full-page"><div id="root"></div><script src="dashboard.js"></script></body></html>`);
const stub = () => `(() => {
  window.__tabs = [];
  const defaults = ${JSON.stringify(defaults)};
  const state = Object.assign({}, defaults, { blockedSites: ["reddit.com"], alwaysBlockedSites: ["youtube.com"], settings: Object.assign({}, defaults.settings, { theme: "${THEME}" }) });
  for (const [k, v] of Object.entries(state)) { if (localStorage.getItem(k) === null) localStorage.setItem(k, JSON.stringify(v)); }
  window.chrome = { runtime: { id: "t", getURL: (p) => "chrome-extension://t/" + p, getManifest: () => ({ version: "1.0.1" }), sendMessage: async () => ({ ok: false, code: "X", message: "x" }) }, tabs: { create: (o) => { window.__tabs.push(o); } } };
})();`;
const results = [];
const check = (n, ok, d) => { results.push(ok); console.log((ok ? "PASS " : "FAIL ") + n + (d ? " :: " + d : "")); };
(async () => {
  const browser = await chromium.launch();
  const ctx = await browser.newContext({ viewport: { width: 400, height: 700 }, deviceScaleFactor: 2 });
  const page = await ctx.newPage();
  const errors = [];
  page.on("pageerror", (e) => errors.push(String(e).slice(0, 300)));
  await page.route("file:///icon.png", (r) => r.fulfill({ path: `${S}/public/icon.png`, contentType: "image/png" }));
  await page.addInitScript(stub());
  await page.goto(`http://127.0.0.1:8765/panel.html`);
  await page.waitForTimeout(600);
  await page.getByRole("tab", { name: "Rules" }).click().catch(async () => { await page.getByRole("button", { name: "Rules" }).first().click(); });
  await page.waitForTimeout(400);
  check("panel: nudge shown", (await page.getByText("No PIN yet.").count()) === 1);
  await page.screenshot({ path: `${OUT}/nudge-panel.png` });
  await page.getByRole("button", { name: "Set a PIN" }).click();
  const tabs = await page.evaluate(() => window.__tabs);
  check("panel: opens Settings in a new tab", tabs.length === 1 && tabs[0].url === "chrome-extension://t/dashboard.html#settings", JSON.stringify(tabs));
  await page.getByRole("button", { name: "Hide this hint" }).click();
  await page.waitForTimeout(200);
  check("panel: hiding removes it", (await page.getByText("No PIN yet.").count()) === 0);
  await page.reload(); await page.waitForTimeout(600);
  await page.getByRole("tab", { name: "Rules" }).click().catch(async () => { await page.getByRole("button", { name: "Rules" }).first().click(); });
  await page.waitForTimeout(300);
  check("panel: stays hidden after a reload", (await page.getByText("No PIN yet.").count()) === 0);
  check("panel: no page errors", errors.length === 0, errors.join(" | "));

  const ctx2 = await browser.newContext({ viewport: { width: 1280, height: 800 } });
  const dash = await ctx2.newPage();
  const errors2 = [];
  dash.on("pageerror", (e) => errors2.push(String(e).slice(0, 300)));
  await dash.route("file:///icon.png", (r) => r.fulfill({ path: `${S}/public/icon.png`, contentType: "image/png" }));
  await dash.addInitScript(stub());
  await dash.goto(`http://127.0.0.1:8765/dashboard.html#rules`);
  await dash.waitForTimeout(700);
  check("dashboard: nudge shown on Rules", (await dash.getByText("No PIN yet.").count()) === 1);
  await dash.screenshot({ path: `${OUT}/nudge-dashboard.png` });
  await dash.getByRole("button", { name: "Set a PIN" }).click();
  await dash.waitForTimeout(400);
  check("dashboard: Set a PIN switches to the Settings tab", (await dash.getByRole("heading", { name: "PIN", exact: true }).count()) === 1 && (await dash.evaluate(() => window.__tabs.length)) === 0);
  check("dashboard: no page errors", errors2.length === 0, errors2.join(" | "));
  await browser.close();
  const failed = results.filter((ok) => !ok).length;
  console.log(`\n${results.length - failed} passed, ${failed} failed`);
  process.exit(failed ? 1 : 0);
})();
