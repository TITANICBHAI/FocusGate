// The idle status card can be hidden (panel and dashboard); the panel settings button opens the full-screen Settings.
const { chromium } = require("playwright");
const fs = require("fs");
const S = "/tmp/claude-0/-home-claude/1d3d810c-0866-503f-8b36-d437fcdf9427/scratchpad/store";
const OUT = process.argv[2];
const THEME = process.argv[3] || "light";
fs.mkdirSync(OUT, { recursive: true });
const defaults = JSON.parse(fs.readFileSync(`${S}/default-state.json`, "utf8"));
const page_html = (name, body) => `<!doctype html><html lang="en" data-theme="${THEME}"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width, initial-scale=1"><title>FocusGate</title><link rel="stylesheet" href="styles.css"></head><body class="${body}"><div id="root"></div><script src="${name}.js"></script></body></html>`;
fs.writeFileSync(`${S}/panel.html`, page_html("panel", "panel-page"));
fs.writeFileSync(`${S}/dashboard.html`, page_html("dashboard", "full-page"));
const stub = () => `(() => {
  window.__tabs = [];
  const defaults = ${JSON.stringify(defaults)};
  const state = Object.assign({}, defaults, { blockedSites: ["reddit.com"], alwaysBlockedSites: [], schedules: [], settings: Object.assign({}, defaults.settings, { theme: "${THEME}" }) });
  for (const [k, v] of Object.entries(state)) { if (localStorage.getItem(k) === null) localStorage.setItem(k, JSON.stringify(v)); }
  window.chrome = { runtime: { id: "t", getURL: (p) => "chrome-extension://t/" + p, getManifest: () => ({ version: "1.0.1" }), sendMessage: async () => ({ ok: false, code: "X", message: "x" }) }, tabs: { create: (o) => { window.__tabs.push(o); } } };
})();`;
const results = [];
const check = (n, ok, d) => { results.push(ok); console.log((ok ? "PASS " : "FAIL ") + n + (d ? " :: " + d : "")); };
(async () => {
  const browser = await chromium.launch();
  const ctx = await browser.newContext({ viewport: { width: 1280, height: 900 }, deviceScaleFactor: 1 });
  const dash = await ctx.newPage();
  const errors = [];
  dash.on("pageerror", (e) => errors.push(String(e).slice(0, 300)));
  await dash.route("**/icon.png", (r) => r.fulfill({ path: `${S}/public/icon.png`, contentType: "image/png" }));
  await dash.addInitScript(stub());
  await dash.goto("http://127.0.0.1:8765/dashboard.html");
  await dash.waitForTimeout(700);
  check("idle card shown", (await dash.getByText("Nothing is blocking right now.").count()) === 1);
  await dash.getByRole("button", { name: "Hide this message" }).click();
  await dash.waitForTimeout(150);
  check("hidden", (await dash.getByText("Nothing is blocking right now.").count()) === 0);
  await dash.getByRole("tab", { name: "Settings" }).click().catch(async () => { await dash.getByText("Settings", { exact: true }).first().click(); });
  await dash.waitForTimeout(400);
  const btn = dash.getByRole("button", { name: "Show hidden messages" });
  check("Settings has the Show hidden messages button", (await btn.count()) === 1);
  check("it explains itself", (await dash.getByText("Bring back the tips and notes you hid with an X or Not now.").count()) === 1);
  await btn.scrollIntoViewIfNeeded();
  await dash.screenshot({ path: `${OUT}/${THEME}-settings-hidden-messages.png` });
  await btn.click();
  await dash.waitForTimeout(300);
  check("a toast says they are back", (await dash.getByText("Hidden messages are back.").count()) >= 1);
  check("the idle card is back on this page without a reload", (await dash.getByText("Nothing is blocking right now.").count()) === 1);
  const stored = await dash.evaluate(() => localStorage.getItem("focusgate.hidden-hints"));
  check("nothing is left hidden in storage", stored === "[]", String(stored));
  await dash.reload(); await dash.waitForTimeout(600);
  check("still shown after a reload", (await dash.getByText("Nothing is blocking right now.").count()) === 1);
  check("no page errors", errors.length === 0, errors.join(" | "));
  await browser.close();
  const failed = results.filter((ok) => !ok).length;
  console.log(`\n${results.length - failed} passed, ${failed} failed`);
  process.exit(failed ? 1 : 0);
})();
