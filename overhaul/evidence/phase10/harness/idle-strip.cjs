// The idle status card can be hidden (panel and dashboard); the panel settings button opens the full-screen Settings.
const { chromium } = require("playwright");
const fs = require("fs");
const S = "/tmp/claude-0/-home-claude/1d3d810c-0866-503f-8b36-d437fcdf9427/scratchpad/store";
const OUT = process.argv[2];
const THEME = process.argv[3] || "light";
fs.mkdirSync(OUT, { recursive: true });
const defaults = JSON.parse(fs.readFileSync(`${S}/default-state.json`, "utf8"));
const page_html = (name, body) => `<!doctype html><html lang="en" data-theme="${THEME}"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width, initial-scale=1"><title>FocusGate</title><link rel="stylesheet" href="styles.css"></head><body class="${body}"><div id="root"></div><script src="${name}.js"></script></body></html>`;
fs.writeFileSync(`${S}/panel.html`, page_html("panel", "panel-page"));
fs.writeFileSync(`${S}/dashboard.html`, page_html("dashboard", "full-page"));
const stub = () => `(() => {
  window.__tabs = [];
  const defaults = ${JSON.stringify(defaults)};
  const state = Object.assign({}, defaults, { blockedSites: ["reddit.com"], alwaysBlockedSites: [], schedules: [], settings: Object.assign({}, defaults.settings, { theme: "${THEME}" }) });
  for (const [k, v] of Object.entries(state)) { if (localStorage.getItem(k) === null) localStorage.setItem(k, JSON.stringify(v)); }
  window.chrome = { runtime: { id: "t", getURL: (p) => "chrome-extension://t/" + p, getManifest: () => ({ version: "1.0.1" }), sendMessage: async () => ({ ok: false, code: "X", message: "x" }) }, tabs: { create: (o) => { window.__tabs.push(o); } } };
})();`;
const results = [];
const check = (n, ok, d) => { results.push(ok); console.log((ok ? "PASS " : "FAIL ") + n + (d ? " :: " + d : "")); };
(async () => {
  const browser = await chromium.launch();
  for (const width of [400, 320]) {
    const ctx = await browser.newContext({ viewport: { width, height: 700 }, deviceScaleFactor: 2 });
    const page = await ctx.newPage();
    const errors = [];
    page.on("pageerror", (e) => errors.push(String(e).slice(0, 300)));
    await page.route("**/icon.png", (r) => r.fulfill({ path: `${S}/public/icon.png`, contentType: "image/png" }));
    await page.addInitScript(stub());
    await page.goto(`http://127.0.0.1:8765/panel.html`);
    await page.waitForTimeout(600);
    const w = `panel ${width}px`;
    check(`${w}: idle card shown`, (await page.getByText("Nothing is blocking right now.").count()) === 1);
    check(`${w}: its action is still there`, (await page.getByRole("button", { name: "Add a schedule" }).count()) === 1);
    const hide = page.getByRole("button", { name: "Hide this message" });
    check(`${w}: hide button present`, (await hide.count()) === 1);
    const box = await page.locator(".fg-nowline").boundingBox();
    const hbox = await hide.boundingBox();
    const head = await page.locator(".fg-nowline__headline").boundingBox();
    check(`${w}: hide button inside the card`, hbox.x >= box.x && hbox.x + hbox.width <= box.x + box.width + 0.5 && hbox.y >= box.y && hbox.y + hbox.height <= box.y + box.height + 0.5, JSON.stringify({ box, hbox }));
    const pad = await page.evaluate(() => parseFloat(getComputedStyle(document.querySelector(".fg-nowline__headline")).paddingRight));
    check(`${w}: headline text stops before the button`, pad >= 32 && head.x + head.width - pad <= hbox.x + 0.5, JSON.stringify({ head, hbox, pad }));
    const settings = page.getByRole("button", { name: "Open settings in full screen" });
    check(`${w}: settings button renamed`, (await settings.count()) === 1 && (await page.getByRole("button", { name: "Open settings", exact: true }).count()) === 0);
    check(`${w}: settings button draws an svg`, (await settings.locator("svg").count()) === 1 && (await settings.locator("svg").getAttribute("aria-hidden")) === "true");
    await page.screenshot({ path: `${OUT}/${THEME}-panel-${width}-idle.png` });
    await settings.click();
    const tabs = await page.evaluate(() => window.__tabs);
    check(`${w}: settings button opens the full-screen Settings`, tabs.length === 1 && tabs[0].url === "chrome-extension://t/dashboard.html#settings", JSON.stringify(tabs));
    await hide.click();
    await page.waitForTimeout(200);
    check(`${w}: hiding removes the card`, (await page.getByText("Nothing is blocking right now.").count()) === 0);
    const gap = await page.evaluate(() => { const el = document.querySelector(".fg-panel__strip"); return el ? getComputedStyle(el).display : "none"; });
    check(`${w}: no empty gap left`, gap === "none", gap);
    await page.screenshot({ path: `${OUT}/${THEME}-panel-${width}-hidden.png` });
    await page.reload(); await page.waitForTimeout(600);
    check(`${w}: stays hidden after a reload`, (await page.getByText("Nothing is blocking right now.").count()) === 0);
    check(`${w}: no page errors`, errors.length === 0, errors.join(" | "));
    await ctx.close();
  }
  const ctx2 = await browser.newContext({ viewport: { width: 1280, height: 800 } });
  const dash = await ctx2.newPage();
  const errors2 = [];
  dash.on("pageerror", (e) => errors2.push(String(e).slice(0, 300)));
  await dash.route("**/icon.png", (r) => r.fulfill({ path: `${S}/public/icon.png`, contentType: "image/png" }));
  await dash.addInitScript(stub());
  await dash.goto(`http://127.0.0.1:8765/dashboard.html`);
  await dash.waitForTimeout(700);
  check("dashboard: idle card shown", (await dash.getByText("Nothing is blocking right now.").count()) === 1);
  await dash.screenshot({ path: `${OUT}/${THEME}-dashboard-idle.png` });
  await dash.getByRole("button", { name: "Hide this message" }).click();
  await dash.waitForTimeout(200);
  check("dashboard: hiding removes the card", (await dash.getByText("Nothing is blocking right now.").count()) === 0);
  await dash.screenshot({ path: `${OUT}/${THEME}-dashboard-hidden.png` });
  await dash.reload(); await dash.waitForTimeout(600);
  check("dashboard: stays hidden after a reload", (await dash.getByText("Nothing is blocking right now.").count()) === 0);
  check("dashboard: no page errors", errors2.length === 0, errors2.join(" | "));
  await browser.close();
  const failed = results.filter((ok) => !ok).length;
  console.log(`\n${results.length - failed} passed, ${failed} failed`);
  process.exit(failed ? 1 : 0);
})();
